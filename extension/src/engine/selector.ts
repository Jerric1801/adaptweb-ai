/**
 * Unique CSS selector generator for DOM elements.
 */

function isAutoGeneratedId(id: string): boolean {
  if (!id || id.trim() === "") return true;
  // React 18 useId `:r1:`, digits at start, long hex or random hashes
  if (id.includes(":") || /^[0-9]/.test(id)) return true;
  if (/^(css|sc|jsx|_)[-_]?[a-z0-9]{4,}$/i.test(id)) return true;
  if (/[a-f0-9]{8,}/i.test(id)) return true;
  if (id.length > 40) return true;
  return false;
}

function getCleanClasses(el: Element): string[] {
  if (!el.className || typeof el.className !== "string") return [];
  const classes = el.className.trim().split(/\s+/);
  return classes.filter((cls) => {
    if (!cls) return false;
    if (/^(css|sc|jsx|_)[-_]?[a-z0-9]{4,}$/i.test(cls)) return false;
    if (/\d{3,}/.test(cls)) return false;
    // skip our own injected classes
    if (cls.startsWith("aw-")) return false;
    return true;
  });
}

function escapeCss(str: string): string {
  if (typeof CSS !== "undefined" && CSS.escape) {
    return CSS.escape(str);
  }
  return str.replace(/([!"#$%&'()*+,.\/:;<=>?@[\\\]^`{|}~])/g, "\\$1");
}

export function uniqueSelector(el: Element, root: Document | Element = document): string {
  if (!(el instanceof Element)) return "";

  // 1. Try #id if unique and not generated
  if (el.id && !isAutoGeneratedId(el.id)) {
    const sel = `#${escapeCss(el.id)}`;
    try {
      if (root.querySelectorAll(sel).length === 1 && root.querySelector(sel) === el) {
        return sel;
      }
    } catch {
      // ignore selector errors
    }
  }

  // 2. Try data-testid / data-test / data-qa / data-cy
  const testAttrs = ["data-testid", "data-test", "data-qa", "data-cy"];
  for (const attr of testAttrs) {
    const val = el.getAttribute(attr);
    if (val) {
      const sel = `[${attr}="${escapeCss(val)}"]`;
      try {
        if (root.querySelectorAll(sel).length === 1 && root.querySelector(sel) === el) {
          return sel;
        }
      } catch {
        // ignore
      }
    }
  }

  // 3. Build path with tag + clean classes or nth-of-type
  const path: string[] = [];
  let curr: Element | null = el;
  let steps = 0;

  while (curr && curr !== root && steps < 5) {
    if (curr.nodeType !== Node.ELEMENT_NODE) break;
    const tag = curr.tagName.toLowerCase();
    if (tag === "body" || tag === "html") break;

    // Check if this ancestor has a reliable ID
    if (curr !== el && curr.id && !isAutoGeneratedId(curr.id)) {
      const ancestorId = `#${escapeCss(curr.id)}`;
      try {
        if (root.querySelectorAll(ancestorId).length === 1) {
          path.unshift(ancestorId);
          break;
        }
      } catch {
        // ignore
      }
    }

    const cleanCls = getCleanClasses(curr);
    let stepSel = tag;
    if (cleanCls.length > 0) {
      stepSel += "." + cleanCls.slice(0, 2).map(escapeCss).join(".");
    }

    // Determine nth-of-type if sibling collision exists
    if (curr.parentElement) {
      const siblings = Array.from(curr.parentElement.children).filter(
        (s) => s.tagName.toLowerCase() === tag,
      );
      if (siblings.length > 1) {
        const index = siblings.indexOf(curr) + 1;
        stepSel += `:nth-of-type(${index})`;
      }
    }

    path.unshift(stepSel);

    // Test if current accumulated path is unique
    const candidate = path.join(" > ");
    try {
      const matches = root.querySelectorAll(candidate);
      if (matches.length === 1 && matches[0] === el) {
        return candidate;
      }
    } catch {
      // ignore
    }

    curr = curr.parentElement;
    steps++;
  }

  const finalCandidate = path.join(" > ");
  if (finalCandidate) {
    try {
      if (root.querySelector(finalCandidate) === el) {
        return finalCandidate;
      }
    } catch {
      // ignore
    }
  }

  // Absolute fallback: tag + index among all matching tags
  const tag = el.tagName.toLowerCase();
  const allOfTag = Array.from(root.querySelectorAll(tag));
  const idx = allOfTag.indexOf(el);
  if (idx !== -1) {
    return `${tag}:nth-of-type(${idx + 1})`;
  }

  return tag;
}
