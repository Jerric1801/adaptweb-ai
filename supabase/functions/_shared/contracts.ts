export type PatternType =
  | "fake_urgency" // countdowns/deadlines that reset or are unverifiable
  | "false_scarcity" // "only 2 left", "selling fast"
  | "fake_social_proof" // "Sarah in Ohio just bought", "37 people viewing"
  | "drip_pricing" // fees/shipping revealed late
  | "sneak_into_basket" // pre-ticked add-ons, warranties, insurance
  | "confirmshaming" // "No thanks, I hate saving money"
  | "nagging_popup" // newsletter/discount/spin-to-win modals on entry
  | "buried_specs" // spec tables hidden behind tabs/accordions (mode feature)
  | "clutter"; // non-essential sections hidden only in certain reading modes

export const PATTERN_LABELS: Record<PatternType, string> = {
  fake_urgency: "Fake urgency",
  false_scarcity: "False scarcity",
  fake_social_proof: "Fake social proof",
  drip_pricing: "Drip pricing",
  sneak_into_basket: "Pre-ticked add-on",
  confirmshaming: "Confirmshaming",
  nagging_popup: "Nagging pop-up",
  buried_specs: "Buried specs",
  clutter: "Clutter",
};

export type RuleAction =
  | "remove" // display:none + dashed ghost placeholder (ghost per settings)
  | "hide" // display:none, no ghost
  | "uncheck" // uncheck checkbox/radio, dispatch change event, annotate
  | "rewrite_text" // replace text with rule.text (e.g. confirmshaming → "No thanks")
  | "annotate_total" // attach True Total card next to selector (drip pricing)
  | "surface" // move/clone element higher on page and expand it (buried specs)
  | "dismiss"; // close modal/overlay: hide it + restore body scroll

export type ReadingMode = "analytical" | "minimalist" | "visual";

export type RuleSource = "curated" | "ai" | "community" | "heuristic";

/* ------------------------------------------------------------------ */
/* Rules                                                               */
/* ------------------------------------------------------------------ */

export interface Rule {
  pattern: PatternType;
  selector: string; // CSS selector, must match ≥1 element, never html/body/main
  action: RuleAction;
  reason?: string; // short human reason shown in UI, e.g. "Timer restarts on reload"
  text?: string; // for rewrite_text
  confidence?: number; // 0..1
  modes?: ReadingMode[]; // if set, rule only applies in these reading modes (e.g. clutter → ["minimalist"])
  extras?: {
    // annotate_total helpers
    shipping_selector?: string;
    fee_selectors?: string[];
    shipping_value?: number; // known flat shipping in major units if not on page
    fee_values?: { label: string; value: number }[];
    tax_rate?: number; // e.g. 0.08 → shown as estimate
    currency?: string; // ISO 4217, default "USD"
  };
}

/** Row in public.site_rules */
export interface SiteRuleSet {
  id?: string;
  domain: string; // registrable host without "www.", e.g. "sharkninja.com"
  path_pattern: string; // "*" or glob like "/products/*"
  rules: Rule[];
  source: RuleSource;
  confidence: number | null;
  version: number;
  updated_at?: string;
}

/* ------------------------------------------------------------------ */
/* Page snapshot (B produces → C forwards → A analyzes)                */
/* Redacted: NO input values, NO emails/addresses, text ≤ 160 chars.   */
/* ------------------------------------------------------------------ */

export interface SnapshotNode {
  selector: string; // unique-ish CSS selector generated by engine
  tag: string;
  text: string; // trimmed, ≤160 chars
  attrs: Record<string, string>; // id, class, role, aria-label, data-* (truncated)
  flags: SnapshotFlag[];
  depth?: number;
}

export type SnapshotFlag =
  | "has_timer_text" // mm:ss / "ends in"
  | "has_scarcity_text"
  | "has_social_proof_text"
  | "has_price"
  | "checkbox_checked"
  | "is_modal"
  | "is_fixed"
  | "is_button"
  | "is_link"
  | "is_table"
  | "is_collapsed";

export interface PriceHit {
  selector: string;
  text: string;
  value: number; // major units
  currency: string;
  kind: "item" | "was" | "shipping" | "fee" | "tax" | "total" | "addon" | "unknown";
}

export interface PageSnapshot {
  url: string; // origin + pathname only (no query/hash)
  domain: string;
  path: string;
  title: string;
  lang: string;
  nodes: SnapshotNode[]; // ≤ 250 most relevant nodes
  prices: PriceHit[];
}

/* ------------------------------------------------------------------ */
/* Engine output                                                       */
/* ------------------------------------------------------------------ */

export interface AppliedChange {
  id: string; // stable per page load
  pattern: PatternType;
  action: RuleAction;
  selector: string;
  reason: string;
  source: RuleSource;
  value_cents?: number; // money surfaced/avoided (fees found, add-on unticked)
  ts: number;
}

export interface TrueTotalPart {
  label: string; // "Item", "Shipping", "Service fee", "Est. tax"
  value: number;
  origin: "page" | "rule" | "estimate";
}

export interface TrueTotal {
  currency: string;
  parts: TrueTotalPart[];
  total: number;
  shownPrice: number; // the headline price on the page
  hiddenDelta: number; // total - shownPrice
}

export interface PageState {
  url: string;
  domain: string;
  enabled: boolean;
  mode: ReadingMode;
  ruleSource: RuleSource | "none";
  changes: AppliedChange[];
  trueTotal: TrueTotal | null;
  analyzing: boolean;
}

