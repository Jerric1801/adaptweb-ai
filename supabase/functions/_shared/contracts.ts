/** content (B) → background (C) via chrome.runtime.sendMessage */
export type ContentToBackground =
  | { type: "GET_CONTEXT"; domain: string; path: string } // → ContextResponse
  | { type: "ANALYZE"; snapshot: PageSnapshot } // → AnalyzeResponse
  | { type: "REPORT"; state: PageState }; // fire-and-forget; C stores per tab + logs events

export interface ContextResponse {
  settings: Settings;
  ruleSets: SiteRuleSet[]; // may be empty → B runs heuristics + may call ANALYZE
}

/** background/popup (C) → content (B) via chrome.tabs.sendMessage */
export type ToContent =
  | { type: "SETTINGS_CHANGED"; settings: Settings }
  | { type: "RULES_UPDATED"; ruleSets: SiteRuleSet[] }
  | { type: "GET_STATE" } // → PageState
  | { type: "UNDO_ALL" } // show original page
  | { type: "REAPPLY" }
  | { type: "HIGHLIGHT"; changeId: string }; // scroll to + flash an applied change

